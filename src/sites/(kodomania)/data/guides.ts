/**
 * Fail the build if a guide links to a host the /click redirect will refuse.
 *
 * `offerHosts` in config.ts is a hand-maintained mirror of the advertisers used
 * here. Miss an entry and the redirect silently 302s the visitor to the home
 * page: no error, no failing test — just every click on that CTA lost while the
 * link still looks like it works. This turns that into a build failure.
 */
function assertOfferHostsCoverEveryLink(): void {
  const allowed: string[] | undefined = activeSiteConfig.offerHosts
  if (!allowed || allowed.length === 0) return

  const covered = (host: string) =>
    allowed.some((entry: string) => host === entry || host.endsWith(`.${entry}`))

  const urls = guides.flatMap((guide) => [
    ...guide.ideas.flatMap((idea) => (idea.clickUrl ? [idea.clickUrl] : [])),
    ...(guide.cta ? [guide.cta.clickUrl] : []),
  ])

  const missing = [
    ...new Set(
      urls
        .map((url) => new URL(url).hostname.replace(/^www\./, '').toLowerCase())
        .filter((host) => !covered(host))
    ),
  ]

  if (missing.length > 0) {
    throw new Error(
      `offerHosts is missing ${missing.join(', ')} — /click would refuse these and redirect visitors home. ` +
        `Add them to offerHosts in src/sites/(kodomania)/config.ts.`
    )
  }
}

assertOfferHostsCoverEveryLink()

