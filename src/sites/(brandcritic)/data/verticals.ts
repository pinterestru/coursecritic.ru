/**
 * Вертикали сайта.
 *
 * Сайт намеренно многовертикальный: один редакционный формат (рейтинговый
 * разбор + страница бренда), применённый к несвязанным рынкам. Вертикаль
 * владеет:
 *   - реестром сервисов  → data/<vertical>/providers.ts
 *   - реестром разборов  → data/<vertical>/articles.ts
 *   - подписью автора    → экспортируется из файла providers
 *
 * Добавить вертикаль — это два файла плюс запись здесь. Компоненты трогать не
 * нужно: они резолвят сервисы по id через data/providers.ts, который сливает
 * все реестры вертикалей.
 */
export type VerticalId = 'retail' | 'cruise' | 'education'

export interface Vertical {
  id: VerticalId
  /** Заголовок раздела, например «Магазины и ритейл». */
  name: string
  /** Короткая метка для чипов и карточек. */
  label: string
  /** Рубрика над H1 разбора, например «Разбор · Ритейл 2026». */
  kicker: string
  /** Позиционирование одной строкой для главной и индекса разборов. */
  blurb: string
  /** Акцентный hex для чипов вертикали. */
  accent: string
  /** Что именно мы проверяем, когда составляем рейтинг в этой вертикали. */
  criteria: string[]
}

